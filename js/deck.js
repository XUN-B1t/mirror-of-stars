  function buildDeck() {
    const cards = MAJOR.map(function (m) {
      return {
        id: "major-" + m.n,
        arcana: "major",
        suit: null,
        suitName: "大阿卡纳",
        rank: m.n,
        numeral: ROMAN[m.n],
        name: m.name,
        en: m.en,
        up: m.up,
        rev: m.rev
      };
    });

    SUITS.forEach(function (suit) {
      RANKS.forEach(function (rank) {
        const meanings = MINOR_MEANINGS[suit.key][rank.key];
        cards.push({
          id: suit.key + "-" + rank.key,
          arcana: "minor",
          suit: suit.key,
          suitName: suit.name,
          element: suit.element,
          domain: suit.domain,
          rankName: rank.label,
          rankEn: rank.en,
          rankKey: rank.key,
          number: rank.n,
          kind: rank.kind,
          numeral: rank.n <= 10 ? String(rank.n) : rank.en.charAt(0),
          name: suit.name + rank.label,
          en: rank.en + " of " + suit.en,
          up: meanings.up,
          rev: meanings.rev
        });
      });
    });

    return cards;
  }

